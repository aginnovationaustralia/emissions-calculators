import { execFileSync, spawnSync } from 'child_process';
import { closeSync, existsSync, mkdtempSync, openSync, rmSync } from 'fs';
import { tmpdir } from 'os';
import { join } from 'path';
import semver from 'semver';

const LOCAL_REF = 'local';

type SpecEntry = {
  version: string;
  ref: string;
  path: string;
};

type VersionMap = Record<string, SpecEntry[]>;

/**
 * Map of calculator name to an ordered list of released OpenAPI specs.
 * Specs are not archived on main; each entry points at the git ref (branch,
 * tag or HEAD) and repo-relative path where that version's spec lives.
 * A ref of "local" reads the spec from the working tree instead, for the
 * unreleased version generated by "pnpm generate:openapi".
 */
const OPENAPI_VERSIONS: VersionMap = {
  combined: [
    {
      version: '3.0.2',
      ref: 'v3.0.2',
      path: 'packages/calculators/openapi/openapi-3.0.2.json',
    },
    {
      version: '4.0.2',
      ref: LOCAL_REF,
      path: 'packages/calculators/openapi/4.0.2/openapi-4.0.2.json',
    },
  ],
};

type CheckResult = 'passed' | 'failed' | 'reported';

function git(args: string[], cwd: string): string {
  return execFileSync('git', args, {
    cwd,
    encoding: 'utf-8',
    stdio: 'pipe',
  }).trim();
}

function tryResolveCommit(candidate: string, repoRoot: string): string | null {
  try {
    return git(
      ['rev-parse', '--verify', '--quiet', `${candidate}^{commit}`],
      repoRoot,
    );
  } catch {
    return null;
  }
}

/**
 * Resolve a map ref to a commit without touching the working tree.
 * Branches are preferred over tags, since a release branch can share its name
 * with a release tag (e.g. v3.0.2) and the spec may only exist on the branch.
 * A branch missing locally (e.g. a shallow CI clone) is fetched from origin.
 */
function resolveRef(ref: string, repoRoot: string): string {
  if (ref === 'HEAD') {
    return git(['rev-parse', 'HEAD'], repoRoot);
  }

  const candidates = [
    `refs/remotes/origin/${ref}`,
    `refs/heads/${ref}`,
    `refs/tags/${ref}`,
    ref,
  ];
  const find = () =>
    candidates
      .map((c) => tryResolveCommit(c, repoRoot))
      .find((c) => c !== null) ?? null;

  const commit = find();
  if (commit) {
    return commit;
  }

  console.log(`  Fetching ${ref} from origin...`);
  // Only the tip is needed; keep shallow CI clones shallow
  const isShallow =
    git(['rev-parse', '--is-shallow-repository'], repoRoot) === 'true';
  const fetch = ['fetch', '--quiet', ...(isShallow ? ['--depth=1'] : [])];
  try {
    git(
      [...fetch, 'origin', `+refs/heads/${ref}:refs/remotes/origin/${ref}`],
      repoRoot,
    );
  } catch {
    git([...fetch, 'origin', `+refs/tags/${ref}:refs/tags/${ref}`], repoRoot);
  }

  const fetched = find();
  if (!fetched) {
    throw new Error(`Could not resolve ref "${ref}"`);
  }
  return fetched;
}

/**
 * Write the spec at commit:path into the scratch directory, without checking
 * out the ref (so the current branch and working tree are left alone).
 * Local entries are read in place from the working tree.
 */
function extractSpec(
  entry: SpecEntry,
  calculator: string,
  repoRoot: string,
  scratchDir: string,
): string {
  if (entry.ref === LOCAL_REF) {
    const localFile = join(repoRoot, entry.path);
    if (!existsSync(localFile)) {
      throw new Error(
        `${entry.path} not found. Run "pnpm generate:openapi" first to generate it.`,
      );
    }
    return localFile;
  }

  const commit = resolveRef(entry.ref, repoRoot);
  const outFile = join(scratchDir, `${calculator}-${entry.version}.json`);
  const fd = openSync(outFile, 'w');
  try {
    const result = spawnSync('git', ['show', `${commit}:${entry.path}`], {
      cwd: repoRoot,
      stdio: ['ignore', fd, 'pipe'],
      encoding: 'utf-8',
    });
    if (result.status !== 0) {
      throw new Error(
        `Could not read ${entry.path} at ${entry.ref} (${commit.slice(0, 8)}): ${result.stderr.trim()}`,
      );
    }
  } finally {
    closeSync(fd);
  }
  return outFile;
}

/**
 * Check if oasdiff is installed and available in PATH
 */
function checkOasdiffInstalled(): boolean {
  try {
    execFileSync('oasdiff', ['--version'], { stdio: 'pipe' });
    return true;
  } catch {
    return false;
  }
}

/**
 * Run oasdiff between two consecutive versions of a calculator's spec.
 * - Patch bump: fail on errors and warnings (strict)
 * - Minor bump: fail on errors only
 * - Major bump: breaking changes are allowed, so they are only reported
 */
function runOasdiffCheck(
  calculator: string,
  base: SpecEntry,
  baseFile: string,
  revision: SpecEntry,
  revisionFile: string,
): CheckResult {
  const bump = semver.diff(base.version, revision.version);
  const isMajor = bump === 'major' || bump === 'premajor';
  const isPatch =
    bump === 'patch' || bump === 'prepatch' || bump === 'prerelease';
  const failOn = isPatch ? 'WARN' : 'ERR';

  console.log(
    `\n[${calculator}] ${base.version} -> ${revision.version} (${bump} bump)`,
  );
  console.log(`  Base:     ${base.ref}:${base.path}`);
  console.log(`  Revision: ${revision.ref}:${revision.path}`);

  if (isMajor) {
    const result = spawnSync(
      'oasdiff',
      ['breaking', '--format', 'json', baseFile, revisionFile],
      { encoding: 'utf-8', maxBuffer: 256 * 1024 * 1024 },
    );
    if (result.status !== 0) {
      console.error(result.stderr || result.stdout);
      console.error(`  ✗ oasdiff could not compare these specs.`);
      return 'failed';
    }
    const changes: unknown[] = JSON.parse(result.stdout || '[]') ?? [];
    console.log(
      `  ℹ ${changes.length} breaking change(s) reported; allowed for a major version bump.`,
    );
    return 'reported';
  }

  console.log(`  Fail on:  ${failOn}`);
  const result = spawnSync(
    'oasdiff',
    ['breaking', '--fail-on', failOn, baseFile, revisionFile],
    { encoding: 'utf-8', maxBuffer: 256 * 1024 * 1024 },
  );
  if (result.stdout?.trim()) {
    console.log(result.stdout);
  }
  if (result.status === 0) {
    console.log('  ✓ No breaking changes detected.');
    return 'passed';
  }
  if (result.stderr?.trim()) {
    console.error(result.stderr);
  }
  console.error(
    result.status === 1
      ? `  ✗ Breaking changes detected! This is not allowed for a ${bump} version bump.`
      : `  ✗ oasdiff could not compare these specs (exit ${result.status}).`,
  );
  return 'failed';
}

function validateVersionMap(map: VersionMap): void {
  for (const [calculator, entries] of Object.entries(map)) {
    for (const entry of entries) {
      if (!semver.valid(entry.version)) {
        throw new Error(`[${calculator}] Invalid version: ${entry.version}`);
      }
    }
    for (let i = 1; i < entries.length; i++) {
      if (!semver.gt(entries[i].version, entries[i - 1].version)) {
        throw new Error(
          `[${calculator}] Versions must be in ascending order: ${entries[i - 1].version} then ${entries[i].version}`,
        );
      }
    }
  }
}

function main(): void {
  // Check if oasdiff is installed
  if (!checkOasdiffInstalled()) {
    console.error('Error: oasdiff is not installed or not in PATH.');
    console.error('Install it from: https://github.com/Tufin/oasdiff');
    console.error('  brew install oasdiff  # macOS');
    console.error('  go install github.com/tufin/oasdiff@latest  # Go');
    process.exit(1);
  }

  validateVersionMap(OPENAPI_VERSIONS);
  const repoRoot = git(['rev-parse', '--show-toplevel'], process.cwd());
  const scratchDir = mkdtempSync(join(tmpdir(), 'openapi-breaking-'));

  const results: CheckResult[] = [];
  try {
    for (const [calculator, entries] of Object.entries(OPENAPI_VERSIONS)) {
      if (entries.length < 2) {
        console.log(
          `\n[${calculator}] Only one version (${entries[0]?.version ?? 'none'}); nothing to compare.`,
        );
        continue;
      }
      const files = entries.map((entry) =>
        extractSpec(entry, calculator, repoRoot, scratchDir),
      );
      for (let i = 1; i < entries.length; i++) {
        results.push(
          runOasdiffCheck(
            calculator,
            entries[i - 1],
            files[i - 1],
            entries[i],
            files[i],
          ),
        );
      }
    }
  } finally {
    rmSync(scratchDir, { recursive: true, force: true });
  }

  const count = (r: CheckResult) => results.filter((x) => x === r).length;
  console.log(
    `\nCompared ${results.length} version pair(s): ${count('passed')} passed, ${count('reported')} major (reported only), ${count('failed')} failed.`,
  );
  if (count('failed') > 0) {
    process.exit(1);
  }
}

main();
