/**
 * Wrapper for getting inlet chemical oxygen demand *CODin,c*
 */
const getInletCOD = (
  wastewater: WastewaterTreatmentInputTransformed,
  constants: HasCommonConstants,
) =>
  (wastewaterInputIsMethod1(wastewater)
    ? captureMethod1Or2Value(
        selectConstant(
          constants.COMMON,
          'WASTEWATER_TREATMENT',
          'COD_BY_COMMODITY',
          wastewater.commodityType,
          'inletCOD',
        ),
        undefined,
      )
    : captureMethod1Or2Value(voidUnit(), wastewater.inletCOD)
  ).named(`CODin,c`);

/**
 * Wrapper for either getting *COD,out* from input, or deriving it from *CODin,c* as per
 * 11.1.1 (3)
 */
const getOutletCOD = (
  wastewater: WastewaterTreatmentInputTransformed,
  constants: HasCommonConstants,
) =>
  (wastewaterInputIsMethod1(wastewater)
    ? captureMethod1Or2Value(
        /**
         * CODout = 0.08 * CODin,c
         */
        getInletCOD(wastewater, constants).multiply(
          num(0.08).reference('11.1.1 (3)'),
        ),
        undefined,
      )
    : captureMethod1Or2Value(voidUnit(), wastewater.outletCOD)
  ).named(`CODout`);

/**
 * Calculate methane generated by wastewater treatment *Qgen*
 * 11.1.1 (2)
 */
const calculateMethaneGeneratedInWastewaterTreatment = (
  wastewater: WastewaterTreatmentInputTransformed,
  constants: HasCommonConstants,
) => {
  const { wastewaterVolume, fractionRemoved } = wastewater;

  const fractionSludge = captureMethod1Or2Value(
    selectConstant(constants.COMMON, 'WASTEWATER_TREATMENT', 'FRAC_SLUDGE'),
    wastewaterInputIsMethod2(wastewater)
      ? wastewater.fractionSludge
      : undefined,
  );
  const inletCOD = getInletCOD(wastewater, constants);
  const outletCod = getOutletCOD(wastewater, constants);

  const facilityWastewaterMCF = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'WASTEWATER_METHANE_CORRECTION_FACTORS',
    wastewater.facilityType,
  ).named(`CFww,t`);

  const wastewaterEF = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'WASTEWATER_EF',
  ).named(`EFww`);

  /**
   * Wt * [CODin * (1 - Fsludge) - CODout] * CFww,t * EFww
   */
  const methaneFromWastewaterTreatedAtFacility = br(
    inletCOD.multiply(oneMinus(fractionSludge)).minus(outletCod),
  )
    .multiply(wastewaterVolume)
    .multiply(facilityWastewaterMCF)
    .multiply(wastewaterEF);

  const facilitySludgeMethaneCorrectionFactor = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_METHANE_CORRECTION_FACTORS',
    wastewater.facilityType,
  ).named(`CFsludge,t`);
  const sludgeEF = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_EF',
  ).named(`EFsludge`);

  /**
   * Wt * [CODin * (Fsludge - Fremoved)] * CFsludge,t * EFsludge
   */
  const methaneFromSludgeTreatedAtFacility = br(
    inletCOD.multiply(br(fractionSludge.minus(fractionRemoved))),
  )
    .multiply(wastewaterVolume)
    .multiply(facilitySludgeMethaneCorrectionFactor)
    .multiply(sludgeEF);

  /**
   * (1/1000) * (
   *  (Wt * [CODin * (1 - Fsludge) - CODout] * CFww,t * EFww) +
   *  (Wt * [CODin * (Fsludge - Fremoved)] * CFsludge,t * EFsludge)
   * )
   */
  const totalMethane = methaneFromWastewaterTreatedAtFacility
    .plus(methaneFromSludgeTreatedAtFacility)
    .named(`Qgen`)
    .reference('11.1.1 (2)');

  return totalMethane;
};

/**
 * Calculate methane emissions produced by wastewater treatment using method 1 (11.1.1)
 */
export const calculateScope1Method1WastewaterCH4 = (
  wastewater: WastewaterTreatmentMethod1InputTransformed,
  context: ExecutionContext,
): Container<Mass<'CH4'>> => {
  const { constants } = context;

  const methaneGenerated = calculateMethaneGeneratedInWastewaterTreatment(
    wastewater,
    constants,
  );

  const fracRecovered = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'COD_BY_COMMODITY',
    wastewater.commodityType,
    'fracRecovered',
  ).named(`Rc`);

  const sludgeBiogasEnergyContentFlared = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_ENERGY_CONTENT',
  ).named(`ECflared`);

  const sludgeBiogasEFCH4 = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_CH4_EF',
  ).named(`EFflared,CH4`);

  const densityOfMethane = selectConstant(
    constants.COMMON,
    'DENSITY_OF_METHANE',
  );

  /**
   * ECH4 = Qgen * (1 - Rc + Rc * (ECflared * EFflared,CH4 / 6.784 * 10^-4 * 1000))
   */
  return methaneGenerated
    .multiply(
      oneMinus(fracRecovered).plus(
        fracRecovered.multiply(
          br(
            sludgeBiogasEFCH4.multiply(sludgeBiogasEnergyContentFlared),
          ).divide(br(densityOfMethane)),
        ),
      ),
    )
    .named('ECH4')
    .reference('11.1.1 (1)');
};

/**
 * Calculate methane emissions produced by wastewater treatment using method 2 (11.1.2)
 */
export const calculateScope1Method2WastewaterCH4 = (
  wastewater: WastewaterTreatmentMethod2InputTransformed,
  context: ExecutionContext,
): Container<Mass<'CH4'>> => {
  const { constants } = context;

  const methaneGenerated = calculateMethaneGeneratedInWastewaterTreatment(
    wastewater,
    constants,
  );

  const { methaneCaptured, methaneFlared, methaneOut } = wastewater;
  const densityOfMethane = selectConstant(
    constants.COMMON,
    'DENSITY_OF_METHANE',
  );

  const totalMethaneCaptured = br(
    methaneCaptured.plus(methaneFlared).plus(methaneOut),
  );

  const sludgeBiogasEnergyContentFlared = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_ENERGY_CONTENT',
  ).named(`ECflared`);

  const sludgeBiogasEFCH4 = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_CH4_EF',
  ).named(`EFflared,CH4`);

  /**
   * 11.1.2 (3)	Where more than 75% of the generated methane emissions are captured,
   * emissions from wastewater management, ECH4 (t CH4), are estimated as:
   *
   * ECH4 = (6.784 * 10^-4 / 3) * (Qcap + Qflared + Qout)
   */
  const totalIf75PercentCaptured = densityOfMethane
    .divide(num(3))
    .multiply(totalMethaneCaptured)
    .reference('11.1.2 (3)');

  /**
   * 11.1.2 (1)	Methane emissions from wastewater management, ECH4 (t CH4), [...], where
   * less than 75% of generated methane emissions are captured, are estimated as:
   *
   * ECH4 = Qgen - (6.784 * 10^-4 * (Qcap + Qflared + Qout)) + (Qflared/1000 * (ECflared * EFflared,CH4))
   */
  const totalOtherwise = methaneGenerated
    .minus(br(densityOfMethane.multiply(totalMethaneCaptured)))
    .plus(
      br(
        sludgeBiogasEFCH4
          .multiply(sludgeBiogasEnergyContentFlared)
          .multiply(methaneFlared),
      ),
    )
    .reference('11.1.2 (1)');

  /**
   * The Method 2 approach in equation 11.1.2 (3) must be employed by any entities where
   * more than 75% of the methane generated is recovered for flaring or combustion
   * purposes, determined if the following holds:
   *
   * 6.784 * 10^-4 * [Qcap + Qflared + Qout] > 0.75 * Qgen
   */
  const moreThan75PercentRecovered = root(
    densityOfMethane
      .multiply(totalMethaneCaptured)
      .unit.store.value.greaterThan(
        methaneGenerated.multiply(num(0.75)).unit.store.value,
      ),
  ).named(`>75% of methane recovered`);
  return ifTrueElse(
    moreThan75PercentRecovered,
    totalIf75PercentCaptured,
    totalOtherwise,
  ).named('ECH4');
};

export const calculateScope1WastewaterCH4 = (
  wastewater: WastewaterTreatmentInputTransformed,
  context: ExecutionContext,
) => {
  return wastewaterInputIsMethod1(wastewater)
    ? captureMethod1Or2Value(
        calculateScope1Method1WastewaterCH4(wastewater, context),
        undefined,
      )
    : captureMethod1Or2Value(
        voidUnit(),
        calculateScope1Method2WastewaterCH4(wastewater, context),
      );
};

/**
 * Calculate nitrous oxide emissions produced by wastewater treatment using method 1
 * (11.1.3)
 */
export const calculateScope1Method1WastewaterN2O = (
  wastewater: WastewaterTreatmentMethod1InputTransformed,
  context: ExecutionContext,
): Container<Mass<'N2O'>> => {
  const { constants } = context;

  const methaneGenerated = calculateMethaneGeneratedInWastewaterTreatment(
    wastewater,
    constants,
  );

  const fracRecovered = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'COD_BY_COMMODITY',
    wastewater.commodityType,
    'fracRecovered',
  ).named(`Rc`);

  const sludgeBiogasEnergyContentFlared = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_ENERGY_CONTENT',
  );

  const sludgeBiogasEFN2O = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_N2O_EF',
  );

  const densityOfMethane = selectConstant(
    constants.COMMON,
    'DENSITY_OF_METHANE',
  );

  /**
   * EN2O = ((Rc * Qgen)/(6.784 * 10^-4 * 1000)) * (ECflared * EFflared,N2O)
   */
  return sludgeBiogasEFN2O
    .multiply(
      sludgeBiogasEnergyContentFlared.multiply(
        methaneGenerated.multiply(fracRecovered).divide(densityOfMethane),
      ),
    )
    .named('EN2O')
    .reference('11.1.3 (1)');
};

/**
 * Calculate nitrous oxide emissions produced by wastewater treatment using method 2
 * (11.1.4)
 */
export const calculateScope1Method2WastewaterN2O = (
  wastewater: WastewaterTreatmentMethod2InputTransformed,
  context: ExecutionContext,
): Container<Mass<'N2O'>> => {
  const { constants } = context;

  const methaneFlared = wastewater.methaneFlared;

  const sludgeBiogasEnergyContentFlared = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_ENERGY_CONTENT',
  );

  const sludgeBiogasEFN2O = selectConstant(
    constants.COMMON,
    'WASTEWATER_TREATMENT',
    'SLUDGE_BIOGAS_N2O_EF',
  );

  /**
   * EN2O = (Qflared/1000) * (ECflared * EFflared,N2O)
   */
  return sludgeBiogasEFN2O
    .multiply(sludgeBiogasEnergyContentFlared.multiply(methaneFlared))
    .named('EN2O')
    .reference('11.1.4 (1)');
};

export const calculateScope1WastewaterN2O = (
  wastewater: WastewaterTreatmentInputTransformed,
  context: ExecutionContext,
) => {
  return wastewaterInputIsMethod1(wastewater)
    ? captureMethod1Or2Value(
        calculateScope1Method1WastewaterN2O(wastewater, context),
        undefined,
      )
    : captureMethod1Or2Value(
        voidUnit(),
        calculateScope1Method2WastewaterN2O(wastewater, context),
      );
};

export const calculate11Scope1WastewaterTreatment = (
  { wastewater }: HasWastewaterTreatmentInputTransformed,
  context: ExecutionContext,
): {
  wastewaterCH4: Container<Mass<'CH4'>>;
  wastewaterN2O: Container<Mass<'N2O'>>;
} => {
  if (wastewater === undefined)
    return {
      wastewaterCH4: zeroCH4,
      wastewaterN2O: zeroN2O,
    };
  return {
    wastewaterCH4: calculateScope1WastewaterCH4(wastewater, context),
    wastewaterN2O: calculateScope1WastewaterN2O(wastewater, context),
  };
};
